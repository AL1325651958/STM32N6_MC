"""Generate MiniCraft UI translations and OFL-licensed 12/16px Chinese glyphs.
python tools/make_minicraft_zh.py --font out/minicraft/fonts/NotoSansSC.ttf
The full upstream font is not shipped; only used glyphs and its OFL notice.
"""
import argparse,json,re
from pathlib import Path
from PIL import Image,ImageDraw,ImageFont
ROOT=Path(__file__).resolve().parents[1]
def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--font',type=Path,required=True);args=parser.parse_args()
    translations=json.loads((ROOT/'tools/minicraft_zh.json').read_text(encoding='utf-8'))
    required=set()
    for name in ('mc_ui.c','mc_play.c','mc_mobs.c','mc_save.c','voxel_game.c'):
        required.update(s for s in re.findall(r'"([^"\n]*)"',(ROOT/'Appli/Core/Src'/name).read_text(encoding='utf-8')) if re.search(r'[A-Z]{2}',s))
    exempt={'N6MC','MC0.SAV','MC1.SAV','MC2.SAV','MC3.SAV'}
    missing=required-set(translations)-exempt
    assert not missing,sorted(missing)
    for en,zh in translations.items():
        assert sorted(re.findall(r'%[-0-9.]*l?[dus%]',en))==sorted(re.findall(r'%[-0-9.]*l?[dus%]',zh)),en
    glyphs=sorted({ord(c) for s in translations.values() for c in s if ord(c)>=128})
    fonts={edge:ImageFont.truetype(str(args.font),edge) for edge in (12,16)}
    lines=['/* Generated by tools/make_minicraft_zh.py. Glyph subset derived from Noto Sans SC, SIL OFL 1.1; see assets/minicraft/NotoSansSC-OFL.txt. */',
           '#ifndef MC_ZH_H','#define MC_ZH_H','typedef struct { const char *en,*zh; } MC_Translation;',
           'static const MC_Translation mc_translations[] = {']
    for en in sorted(translations):lines.append('  {'+json.dumps(en,ensure_ascii=False)+','+json.dumps(translations[en],ensure_ascii=False)+'},')
    lines+=['};','typedef struct { uint16_t codepoint; uint16_t large[16],small[12]; } MC_Hanzi;','static const MC_Hanzi mc_hanzi[] = {']
    for cp in glyphs:
        arrays=[]
        for edge in (16,12):
            font=fonts[edge];box=font.getbbox(chr(cp));im=Image.new('L',(edge,edge));draw=ImageDraw.Draw(im)
            draw.text((-box[0]+(edge-(box[2]-box[0]))//2,-box[1]+(edge-(box[3]-box[1]))//2),chr(cp),font=font,fill=255)
            arrays.append('{'+','.join('0x%04x'%sum((1<<(edge-1-x)) for x in range(edge) if im.getpixel((x,y))>=100) for y in range(edge))+'}')
        lines.append('  {0x%04x,%s,%s},'%(cp,*arrays))
    lines+=['};','#endif','']
    (ROOT/'Appli/Core/Inc/mc_zh.h').write_text('\n'.join(lines),encoding='utf-8')
    print('Generated',len(translations),'translations and',len(glyphs),'Chinese glyphs')
if __name__=='__main__':main()
