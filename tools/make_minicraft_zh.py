"""Build and audit native-size Chinese glyphs; full fonts stay in out.
Use --font NotoSansSC.ttf --pixel-font ark-pixel-12px-monospaced-zh_hans.ttf.
Add --check to verify the generated header without rewriting it.
"""
import argparse
import hashlib
import json
import re
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
from fontTools.ttLib import TTFont
ROOT = Path(__file__).resolve().parents[1]
WEIGHT, THRESHOLD = 500, 100
SMALL_FALLBACK = {0x6D46, 0x71C3}  # 浆 and 燃: absent from the pinned Ark 12px build.


def render(font, cp, edge, pixel):
    box = font.getbbox(chr(cp))
    x, y = (0, 0) if pixel else (-box[0]+(edge-box[2]+box[0])//2,
                                -box[1]+(edge-box[3]+box[1])//2)
    pad = 8
    canvas = Image.new('L', (edge+2*pad, edge+2*pad))
    ImageDraw.Draw(canvas).text((pad+x, pad+y), chr(cp), font=font, fill=255)
    binary = canvas.point(lambda v: 255 if v >= THRESHOLD else 0)
    tile = binary.crop((pad, pad, pad+edge, pad+edge))
    outside = binary.copy()
    ImageDraw.Draw(outside).rectangle((pad,pad,pad+edge-1,pad+edge-1), fill=0)
    assert not outside.getbbox(), ('clipped glyph', chr(cp), edge, box)
    assert tile.getbbox(), ('empty glyph', chr(cp), edge)
    rows = [sum(1 << (edge-1-x) for x in range(edge) if tile.getpixel((x,y)))
            for y in range(edge)]
    return rows, tile


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--font', type=Path, required=True)
    parser.add_argument('--pixel-font', type=Path, required=True)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--audit-dir', type=Path, default=ROOT/'out/minicraft/font-audit')
    args = parser.parse_args()
    sources = json.loads((ROOT/'tools/minicraft_font_sources.json').read_text(encoding='utf-8'))
    cmaps = {}
    for key,path in [('noto',args.font),('ark12',args.pixel_font)]:
        assert hashlib.sha256(path.read_bytes()).hexdigest() == sources[key]['sha256'], ('font hash',key)
        with TTFont(path) as source:
            cmaps[key] = source.getBestCmap()
    translations = json.loads((ROOT/'tools/minicraft_zh.json').read_text(encoding='utf-8'))
    required = set()
    for name in ('mc_ui.c','mc_play.c','mc_mobs.c','mc_save.c','voxel_game.c'):
        required.update(s for s in re.findall(r'"([^"\n]*)"',(ROOT/'Appli/Core/Src'/name).read_text(encoding='utf-8')) if re.search(r'[A-Z]{2}',s))
    exempt = {'N6MC','MC0.SAV','MC1.SAV','MC2.SAV','MC3.SAV'}
    assert not required-set(translations)-exempt, sorted(required-set(translations)-exempt)
    for en,zh in translations.items():
        assert sorted(re.findall(r'%[-0-9.]*l?[dus%]',en)) == sorted(re.findall(r'%[-0-9.]*l?[dus%]',zh)), en
    glyphs = sorted({ord(c) for s in translations.values() for c in s if ord(c)>=128})
    fonts = {edge:ImageFont.truetype(str(args.font),edge) for edge in (12,16)}
    for font in fonts.values():font.set_variation_by_axes([WEIGHT])
    pixel_font = ImageFont.truetype(str(args.pixel_font),12)
    missing = set(glyphs)-cmaps['ark12'].keys()
    assert missing == SMALL_FALLBACK, ('review small-font coverage changes',sorted(missing))
    lines = ['/* Generated by tools/make_minicraft_zh.py. Used subsets: Noto Sans SC Medium and Ark Pixel 12px zh-Hans, SIL OFL 1.1; licenses in assets/minicraft/. */',
             '#ifndef MC_ZH_H','#define MC_ZH_H','typedef struct { const char *en,*zh; } MC_Translation;',
             'static const MC_Translation mc_translations[] = {']
    for en in sorted(translations):lines.append('  {'+json.dumps(en,ensure_ascii=False)+','+json.dumps(translations[en],ensure_ascii=False)+'},')
    lines += ['};','typedef struct { uint16_t codepoint; uint16_t large[16],small[12]; } MC_Hanzi;','static const MC_Hanzi mc_hanzi[] = {']
    audit = []
    for cp in glyphs:
        arrays = []
        for edge in (16,12):
            pixel = edge==12 and cp not in SMALL_FALLBACK
            key = 'ark12' if pixel else 'noto'
            assert cp in cmaps[key] and cmaps[key][cp]!='.notdef', ('missing source glyph',cp,edge)
            rows,tile = render(pixel_font if pixel else fonts[edge],cp,edge,pixel)
            arrays.append('{'+','.join('0x%04x'%v for v in rows)+'}')
            audit.append({'character':chr(cp),'codepoint':'U+%04X'%cp,'size':edge,'source':key,
                          'glyph':cmaps[key][cp],'weight':None if pixel else WEIGHT,
                          'ink_pixels':sum(v.bit_count() for v in rows),'bbox':tile.getbbox(),
                          'clipped':False,'bitmap_sha256':hashlib.sha256(tile.tobytes()).hexdigest()})
        lines.append('  {0x%04x,%s,%s},'%(cp,*arrays))
    lines += ['};','#endif','']
    data = '\n'.join(lines)
    header = ROOT/'Appli/Core/Inc/mc_zh.h'
    if args.check:assert header.read_text(encoding='utf-8')==data, 'generated header is stale'
    else:header.write_text(data,encoding='utf-8')
    args.audit_dir.mkdir(parents=True,exist_ok=True)
    report = {'translations':len(translations),'characters':len(glyphs),'glyphs_checked':len(audit),
              'noto_weight':WEIGHT,'threshold':THRESHOLD,'sources':sources,'glyphs':audit}
    (args.audit_dir/'glyph-audit.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    print('Verified',len(translations),'translations and',len(audit),'glyphs; no missing source glyphs, empty tiles or clipped pixels')


if __name__=='__main__':main()
